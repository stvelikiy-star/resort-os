import React from 'react';
import {Alert} from 'react-native';
import {act,fireEvent,render,waitFor} from '@testing-library/react-native';
import '../src/i18n';
import StoreWorkspace from '../app/(app)/store';
import {ThemeProvider} from '../src/theme/ThemeProvider';
import type {StockReceipt} from '../src/api/stockReceipt';
const ID='11111111-1111-4111-8111-111111111111',ITEM='22222222-2222-4222-8222-222222222222';
const mockRecords=new Map<string,string>();const movements=new Map<string,StockReceipt>();
const mockSend=jest.fn();
const mockModules={kitchenStock:jest.fn(async()=>({items:[{id:ITEM,name:'Rice',unit:'KG',balance:'0',cost_per_unit_kgs:'2.5',is_sample:false}],new_receipt_movement_id:ID})),receiveKitchenStock:mockSend};
jest.mock('../src/lib/storage',()=>({getDurableItem:async(k:string)=>mockRecords.get(k)??null,setDurableItem:async(k:string,v:string)=>{mockRecords.set(k,v);},removeDurableItem:async(k:string)=>{mockRecords.delete(k);}}));
jest.mock('../src/state/session',()=>({useSession:()=>({user:{id:'store',role:'STORE_STAFF',module_permissions:['DINING']},hotel:{id:'hotel.example'},api:{mode:'LIVE'},locale:'en',serverAuthMode:'single_property'})}));
jest.mock('../src/api/liveModules',()=>({useLiveModules:()=>mockModules}));
jest.mock('../src/components/KitchenProcurement',()=>({KitchenProcurement:()=>null}));
jest.mock('../src/components/KitchenLosses',()=>({KitchenLosses:()=>null}));
jest.mock('expo-router',()=>({useFocusEffect:()=>{}}));
jest.mock('react-native-safe-area-context',()=>({useSafeAreaInsets:()=>({top:0,bottom:0,left:0,right:0})}));
const screen=()=> <ThemeProvider initial="light"><StoreWorkspace/></ThemeProvider>;
beforeEach(()=>{mockRecords.clear();movements.clear();mockSend.mockReset();jest.spyOn(Alert,'alert').mockImplementation(()=>{});});
afterEach(()=>jest.restoreAllMocks());
test('timeout after commit -> remount -> explicit same-ID replay; only one movement',async()=>{
 mockSend.mockImplementation(async(p:StockReceipt)=>{const replay=movements.has(p.movement_id);movements.set(p.movement_id,p);if(!replay)throw new Error('lost acknowledgement');return {id:p.movement_id,stock_item_id:p.stock_item_id,quantity:'10.000000',already_processed:true,unit_cost_kgs:'2.5000',payment_created:false};});
 const view=await render(screen());await waitFor(()=>expect(view.getByText('Rice (KG)')).toBeTruthy());
 await fireEvent.press(view.getByText('Rice (KG)'));await fireEvent.changeText(view.getByLabelText('Quantity'),'10');
 await fireEvent.press(view.getByTestId('stock-receipt-save'));
 const confirm=jest.mocked(Alert.alert).mock.calls.at(-1)?.[2]?.find(x=>x.style!=='cancel')?.onPress;
 await act(async()=>{await confirm?.();});
 await waitFor(()=>expect(view.getByTestId('stock-receipt-pending')).toBeTruthy());await view.unmount();
 const reopened=await render(screen());await waitFor(()=>expect(reopened.getByTestId('stock-receipt-retry')).toBeEnabled());
 expect(reopened.getByTestId('stock-receipt-save')).toBeDisabled();
 await fireEvent.press(reopened.getByTestId('stock-receipt-retry'));
 await waitFor(()=>expect(reopened.queryByTestId('stock-receipt-pending')).toBeNull());
 expect(mockSend).toHaveBeenCalledTimes(2);expect(mockSend.mock.calls[0][0]).toEqual(mockSend.mock.calls[1][0]);expect(movements.size).toBe(1);
});
