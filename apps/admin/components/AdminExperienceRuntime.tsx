function translateDynamicFragments(value: string, locale: Locale): string {
  if (locale === "ru") return value;
  let result = value;
  for (const fragment of DYNAMIC_FRAGMENTS) {
    if (result.includes(fragment.ru)) result = result.split(fragment.ru).join(fragment[locale]);
  }
  return result;
}

